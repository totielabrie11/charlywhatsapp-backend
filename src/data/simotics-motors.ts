function tension(kw: number): string {
  return kw <= 0.75 ? "230/400 V Δ/Y" : "400/690 V Δ/Y";
}

function orderCode(kw: number, poles: number): string {
  // Siemens SIMOTICS GP 1LE1 — patrón de familia (no código completo)
  if (kw <= 3) return `1LE1001-${poles}xxx-xxxx`;
  if (kw <= 22) return `1LE1002-${poles}xxx-xxxx`;
  if (kw <= 90) return `1LE1003-${poles}xxx-xxxx`;
  return `1LE1004-${poles}xxx-xxxx`;
}

function build(
  kw: number, hp: number, poles: number,
  frame: string, rpm: number, currentA: number,
  cosPhi: number, etaPct: number, weightKg: number,
  bearDE: string, bearNDE: string,
): MotorSpec {
  return {
    kw, hp, poles, frame,
    shaftHeightMm: FRAME_SHAFT_HEIGHT[frame] ?? 0,
    shaftDiameterMm: FRAME_SHAFT_DIAM[frame] ?? 0,
    rpm50hz: rpm,
    currentA400V: currentA,
    cosPhi,
    efficiencyIE3: etaPct,
    weightKg,
    mounting: FRAME_MOUNTING[frame] ?? ["B3", "B5"],
    ip: "IP55",
    insulationClass: "F",
    cooling: "IC411",
    service: "S1",
    tensionV: tension(kw),
    bearingDE: bearDE,
    bearingNDE: bearNDE,
    ambientTempC: 40,
    altitudeM: 1000,
    orderCodeBase: orderCode(kw, poles),
  };
}

